# -*- coding: utf-8 -*-
"""Builds the Arabic user guide (docx with RTL formatting) then it gets
converted to PDF via LibreOffice. Plain-language description of every
feature in the app, written for a non-technical reader -- no mention of
programming languages, frameworks, or any implementation detail."""
import docx
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement
from docx.shared import Pt, RGBColor, Cm

FONT = "DejaVu Sans"

def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi")
    pPr.append(bidi)

def set_run_rtl(run):
    rPr = run._r.get_or_add_rPr()
    rtl = OxmlElement("w:rtl")
    rPr.append(rtl)

def add_par(doc, text, size=12, bold=False, color=None, align=WD_ALIGN_PARAGRAPH.RIGHT,
            space_after=8, space_before=0):
    p = doc.add_paragraph()
    p.alignment = align
    set_rtl(p)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    run = p.add_run(text)
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    set_run_rtl(run)
    rPr = run._r.get_or_add_rPr()
    rFonts = OxmlElement("w:rFonts")
    rFonts.set(qn("w:cs"), FONT)
    rPr.append(rFonts)
    return p

def add_heading(doc, text, size=17, color=(0x1a, 0x56, 0x8a)):
    return add_par(doc, text, size=size, bold=True, color=color, space_before=18, space_after=10)

def add_subheading(doc, text, size=13.5, color=(0x1a, 0x56, 0x8a)):
    return add_par(doc, text, size=size, bold=True, color=color, space_before=10, space_after=6)

def add_body(doc, text, size=11.5):
    return add_par(doc, text, size=size, space_after=8)

def add_rule(doc):
    p = doc.add_paragraph()
    set_rtl(p)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(4)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "1a568a")
    pBdr.append(bottom)
    pPr.append(pBdr)

